"""Export skinning sources from Raynna's pinned cMaNGOS Classic SQL snapshot."""

import argparse
from collections import defaultdict
import gzip
import hashlib
import json
from pathlib import Path
import re


SOURCE_BLOB = "0a77f5230a3d5d6db968678203dfe3b30c34b8a9"
SQL_TOKEN = re.compile(r"'(?:\\.|[^'\\])*'|NULL|-?\d+(?:\.\d+)?")
SQL_ROW = re.compile(r"\(((?:'(?:\\.|[^'\\])*'|[^'()])*)\)")


def rows(sql, table):
    for line in sql.splitlines():
        if not line.startswith('INSERT INTO `' + table + '` VALUES '):
            continue
        for match in SQL_ROW.finditer(line):
            values = []
            for token in SQL_TOKEN.findall(match[1]):
                if token.startswith("'"):
                    values.append(re.sub(r'\\(.)', r'\1', token[1:-1]))
                elif token == 'NULL':
                    values.append(None)
                else:
                    values.append(float(token) if '.' in token else int(token))
            yield values


def lua(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='ClassicDB_1_12_1_z2815.sql.gz')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[3]
                        / 'addon/forerver/wow_tools/raynna_bestiary/SkinningReference.lua')
    args = parser.parse_args()
    blob = args.source.read_bytes()
    fingerprint = hashlib.sha1(b'blob ' + str(len(blob)).encode() + b'\0' + blob).hexdigest()
    if fingerprint != SOURCE_BLOB:
        raise ValueError('Input does not match the adopted Classic loot reference snapshot')
    sql = gzip.decompress(blob).decode('utf8')
    schema = re.search(r'CREATE TABLE `creature_template` \((.*?)\n\)', sql, re.S)[1]
    columns = re.findall(r'^  `([^`]+)`', schema, re.M)
    creatures = {}
    for row in rows(sql, 'creature_template'):
        creature = dict(zip(columns, row))
        if creature['SkinningLootId']:
            creatures[creature['Entry']] = [creature['SkinningLootId'], creature['Name'],
                                            creature['MinLevel'], creature['MaxLevel']]
    loot = defaultdict(list)
    names = {}
    for entry, item, chance, group, minimum, maximum, condition, comment in rows(sql, 'skinning_loot_template'):
        loot[entry].append([item, chance, group, minimum, maximum, condition])
        if minimum > 0 and comment:
            names[item] = comment
    missing = {npc[0] for npc in creatures.values()} - loot.keys()
    if missing:
        raise ValueError('Missing skinning loot tables: ' + str(sorted(missing)))
    # References resolve against LootReference.lua, generated from the same pinned blob.
    references = {row[0] for row in rows(sql, 'reference_loot_template')}
    for records in loot.values():
        for row in records:
            if row[3] < 0 and -row[3] not in references:
                raise ValueError('Missing reference loot table: ' + str(-row[3]))
    output = [
        'WoWTools.raynnaBestiary.RegisterSource(function(...)',
        '-- Generated by skills/wow-tools/scripts/build_skinning_reference.py.',
        '-- cMaNGOS Classic DB, GPL-3.0. See REFERENCE-SOURCES.txt.',
        '-- Classic skinning reference; Forever coverage and probabilities may differ.',
        'local _, A = ...',
        'A.SkinningReference = {creatures={}, loot={}, names={}}',
        'local D = A.SkinningReference',
    ]
    for field, records in [('loot', loot), ('creatures', creatures)]:
        for key, values in sorted(records.items()):
            if field == 'loot':
                value = ','.join('{' + ','.join(map(lua, row)) + '}' for row in values)
            else:
                value = ','.join(map(lua, values))
            output.append('D.' + field + '[' + str(key) + ']={' + value + '}')
    for item, name in sorted(names.items()):
        output.append('D.names[' + str(item) + ']=' + lua(name))
    output.append('end)')
    args.output.write_text('\n'.join(output) + '\n', encoding='utf8')
    print(f'Generated {len(creatures)} creatures, {len(loot)} skinning tables, {len(names)} named items.')


if __name__ == '__main__':
    main()
